use cavalier_contours::polyline::{PlineCreation, PlineSource, PlineSourceMut, Polyline};
use cnc_kernel::offset::offset_region;

fn pline(points: &[(f64, f64, f64)]) -> Polyline<f64> {
    let mut p = Polyline::with_capacity(points.len(), true);
    for &(x, y, b) in points {
        p.add(x, y, b);
    }
    p
}

/// A bold "e" from Roboto as biarcs (outline and its eye): shrunk, the eye
/// grows and stays a hole. Its eye has a segment 12 nm long, which made
/// CavalierContours' shape offset drop it.
#[test]
fn shrinking_keeps_the_hole_of_an_e() {
    let (outer, hole) = e();
    let shrunk = offset_region(&[outer, hole], -1.002);
    let areas: Vec<f64> = shrunk.iter().map(|p| p.area()).collect();
    assert_eq!(shrunk.len(), 2, "{:?}", areas);
    assert!(areas.iter().any(|a| *a < -20.0), "{:?}", areas);
}

